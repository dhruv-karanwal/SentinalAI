"""``export-paper-assets``: paper tables and figures computed from run files, never typed in.

Why: every number in the paper must be traceable to a run directory. This
module reads the ``per_case`` blocks of finished matched runs
(:func:`app.study.final_runs.case_rows`), separately for the dev pilot
(``study_part = pilot``, labelled "pilot, not paper results") and the
held-out study (``study_part = held-out``), and writes into ``results/``:

- ``<part>/per_case.csv``: one row per (case, variant, score row): the raw
  material of everything else;
- ``<part>/summary.csv`` / ``summary.tex``: per (truncation, repeat, variant,
  score row): reachable attack cases, headline coverage (event_label,
  reachable) with a 95 % percentile bootstrap CI over cases (stratified by
  scenario, seeded from statistics.json), time-label coverage, pooled
  citation precision (event_label), pooled unsupported-claim rate, verdict
  accuracy, failed cases, mean tokens per case;
- ``<part>/comparisons.csv`` / ``comparisons.tex``: the declared family of
  ``experiments/config/statistics.json`` on the primary truncation and repeat
  (paired bootstrap + Holm, :mod:`app.study.stats`);
- ``<part>/coverage.svg``: headline coverage per variant, single vs graph
  after the verifier, with the CI whiskers (static figure; ``<title>`` on
  every bar gives the exact value on hover);
- ``<part>/provenance.json``: the run ids and config hashes used;
- ``results/README.md``: what each file is and how it was made.
"""

from __future__ import annotations

import csv
import json
import sys
from collections.abc import Callable, Mapping, Sequence
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from app.study.final_runs import case_rows
from app.study.revisions import select_rows
from app.study.stats import compare_family, load_statistics_config, paired_bootstrap

REPO = Path(__file__).resolve().parents[3]
DEFAULT_STATISTICS = REPO / "experiments" / "config" / "statistics.json"
PARTS = {"pilot": "pilot", "held-out": "held_out"}
LABELS = {"pilot": "DEV PILOT (pilot, not paper results)",
          "held-out": "HELD-OUT STUDY (final runs after the protocol freeze)"}
ARM_ORDER = ("single", "single+verifier", "graph", "graph+verifier")
SERIES = (("single+verifier", "#2a78d6"), ("graph+verifier", "#eb6834"))  # categorical slots 1, 2


def _mean(values: Sequence[float]) -> float | None:
    return sum(values) / len(values) if values else None


def _fmt(x: Any, digits: int = 3) -> str:
    if x is None:
        return ""
    if isinstance(x, float):
        return f"{x:.{digits}f}"
    return str(x)


def _write_csv(rows: Sequence[Mapping[str, Any]], path: Path) -> None:
    fields: list[str] = []
    for r in rows:
        fields.extend(k for k in r if k not in fields)
    with path.open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields, lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({k: ("" if r.get(k) is None else r.get(k)) for k in fields})


def _tex_escape(s: str) -> str:
    for a, b in (("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("_", "\\_"),
                 ("#", "\\#"), ("$", "\\$")):
        s = s.replace(a, b)
    return s


def _write_tex(rows: Sequence[Mapping[str, Any]], columns: Sequence[tuple[str, str]], caption: str,
               path: Path) -> None:
    lines = ["% generated by export-paper-assets from run files; do not edit by hand",
             "\\begin{table}[t]", "\\centering", f"\\caption{{{_tex_escape(caption)}}}",
             "\\begin{tabular}{" + "l" * 2 + "r" * (len(columns) - 2) + "}", "\\hline",
             " & ".join(_tex_escape(h) for _, h in columns) + " \\\\", "\\hline"]
    for r in rows:
        lines.append(" & ".join(_tex_escape(_fmt(r.get(k))) for k, _ in columns) + " \\\\")
    lines += ["\\hline", "\\end{tabular}", "\\end{table}", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def summarize(rows: Sequence[Mapping[str, Any]], seed: int, resamples: int,
              confidence: float) -> list[dict[str, Any]]:
    groups: dict[tuple[str, int, str, str], list[Mapping[str, Any]]] = {}
    for r in rows:
        groups.setdefault((r["truncation"], r["repeat"], r["variant"], r["arm"]), []).append(r)

    def order(k: tuple[str, int, str, str]) -> tuple[str, int, str, int]:
        return (k[0], k[1], k[2], ARM_ORDER.index(k[3]) if k[3] in ARM_ORDER else 99)

    out = []
    for key in sorted(groups, key=order):
        g = groups[key]
        reach = [r for r in g if r["coverage_event_reachable"] is not None]
        cov = [float(r["coverage_event_reachable"]) for r in reach]
        ci = paired_bootstrap([0.0] * len(cov), cov, seed=seed, resamples=resamples,
                              confidence=confidence, strata=[r["scenario"] for r in reach]) if cov else None
        cited = sum(int(r["cited"]) for r in g)
        attack_cited = sum(round(float(r["citation_precision_event"]) * int(r["cited"]))
                           for r in g if r["citation_precision_event"] is not None)
        claims = sum(int(r["claims"]) for r in g)
        unsupported = sum(int(r["unsupported_claims"]) for r in g)
        out.append({
            "truncation": key[0], "repeat": key[1], "variant": key[2], "arm": key[3],
            "scenarios": len({r["scenario"] for r in g}), "cases": len(g), "cases_reachable": len(reach),
            "coverage_event_reachable": _mean(cov),
            "coverage_ci_low": ci.ci_low if ci else None, "coverage_ci_high": ci.ci_high if ci else None,
            "coverage_time_reachable": _mean([float(r["coverage_time_reachable"]) for r in reach]),
            "citation_precision_event": attack_cited / cited if cited else None,
            "cited": cited, "claims": claims,
            "unsupported_claim_rate": unsupported / claims if claims else None,
            "verdict_accuracy": _mean([float(r["verdict_correct"]) for r in g]),
            "failed_cases": sum(1 for r in g if r["status"] == "failed"),
            "budget_hit_cases": sum(1 for r in g if str(r["status"]).endswith("budget_exceeded")),
            "mean_tokens_per_case": _mean([float(r["input_tokens"]) + float(r["output_tokens"]) for r in g]),
        })
    return out


def _svg(summary: Sequence[Mapping[str, Any]], title: str, truncation: str, repeat: int) -> str:
    rows = [r for r in summary if r["truncation"] == truncation and r["repeat"] == repeat]
    variants = list(dict.fromkeys(r["variant"] for r in rows))
    by = {(r["variant"], r["arm"]): r for r in rows}
    w, h, left, top, bottom = 720, 360, 56, 56, 64
    plot_w, plot_h = w - left - 16, h - top - bottom
    group = plot_w / max(1, len(variants))
    bar = min(28.0, group / 3)

    def y(v: float) -> float:
        return top + plot_h * (1 - v)

    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
           f'font-family="Helvetica, Arial, sans-serif" font-size="12" role="img" '
           f'aria-label="{title}">',
           f'<rect width="{w}" height="{h}" fill="#ffffff"/>',
           f'<text x="{left}" y="20" font-size="14" font-weight="600" fill="#1a1a19">{title}</text>',
           f'<text x="{left}" y="38" fill="#5f5e5a">Coverage by event_label on reachable phases, '
           f'{truncation} truncation, repeat {repeat}; whiskers: 95% bootstrap CI</text>']
    for t in (0.0, 0.25, 0.5, 0.75, 1.0):
        out.append(f'<line x1="{left}" x2="{w - 16}" y1="{y(t):.1f}" y2="{y(t):.1f}" stroke="#e4e3dd" '
                   f'stroke-width="1"/>')
        out.append(f'<text x="{left - 8}" y="{y(t) + 4:.1f}" text-anchor="end" fill="#5f5e5a">{t:.2f}</text>')
    for gi, v in enumerate(variants):
        cx = left + group * gi + group / 2
        for si, (arm, color) in enumerate(SERIES):
            r = by.get((v, arm))
            if r is None or r["coverage_event_reachable"] is None:
                continue
            val = float(r["coverage_event_reachable"])
            x = cx + (si - 1) * (bar + 2) + 1
            top_y = y(val)
            height = max(0.0, y(0) - top_y)
            out.append(f'<g><title>{v} / {arm}: {val:.3f} ({r["cases_reachable"]} reachable cases, '
                       f'CI {_fmt(r["coverage_ci_low"])}-{_fmt(r["coverage_ci_high"])})</title>'
                       f'<path d="M{x:.1f},{y(0):.1f} V{top_y + min(4, height):.1f} '
                       f'Q{x:.1f},{top_y:.1f} {x + 4:.1f},{top_y:.1f} H{x + bar - 4:.1f} '
                       f'Q{x + bar:.1f},{top_y:.1f} {x + bar:.1f},{top_y + min(4, height):.1f} '
                       f'V{y(0):.1f} Z" fill="{color}"/></g>')
            if r["coverage_ci_low"] is not None and r["coverage_ci_high"] is not None:
                mx = x + bar / 2
                lo, hi = y(float(r["coverage_ci_low"])), y(float(r["coverage_ci_high"]))
                out.append(f'<path d="M{mx:.1f},{lo:.1f} V{hi:.1f} M{mx - 4:.1f},{lo:.1f} H{mx + 4:.1f} '
                           f'M{mx - 4:.1f},{hi:.1f} H{mx + 4:.1f}" stroke="#1a1a19" stroke-width="1.5" '
                           f'fill="none"/>')
        out.append(f'<text x="{cx:.1f}" y="{y(0) + 18:.1f}" text-anchor="middle" fill="#1a1a19">{v}</text>')
    out.append(f'<line x1="{left}" x2="{w - 16}" y1="{y(0):.1f}" y2="{y(0):.1f}" stroke="#8a8984"/>')
    lx = left
    for arm, color in SERIES:
        out.append(f'<rect x="{lx}" y="{h - 22}" width="12" height="12" rx="2" fill="{color}"/>'
                   f'<text x="{lx + 18}" y="{h - 12}" fill="#1a1a19">{arm}</text>')
        lx += 150
    out.append("</svg>")
    return "\n".join(out) + "\n"


def export_paper_assets(runs_dir: str | Path, results_dir: str | Path, *,
                        statistics_config: str | Path = DEFAULT_STATISTICS,
                        freeze_path: str | Path | None = None,
                        prompt_version: str | None = None,
                        on_warning: Callable[[str], None] | None = None) -> list[str]:
    warn = on_warning or (lambda msg: print(f"WARNING: {msg}", file=sys.stderr))
    stats = load_statistics_config(statistics_config)
    raw = json.loads(Path(statistics_config).read_text(encoding="utf-8"))
    primary_t = str(raw.get("primary_truncation", "spread"))
    primary_r = int(raw.get("primary_repeat", 1))
    out = Path(results_dir)
    out.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    readme_parts: list[str] = []
    for part, folder in PARTS.items():
        rows = case_rows(runs_dir, [part]) if Path(runs_dir).exists() else []
        label = LABELS[part]
        # one prompt revision per part (default: the latest); see app/study/revisions.py
        rows, choice = select_rows(rows, runs_dir, prompt_version)
        if choice.warning:
            warn(f"{label}: {choice.warning}")
        if not rows:
            readme_parts.append(f"## {label}\n\nno finished runs of this part were found in "
                                f"`{Path(runs_dir).as_posix()}` when the exporter ran.\n")
            continue
        d = out / folder
        d.mkdir(parents=True, exist_ok=True)
        _write_csv(rows, d / "per_case.csv")
        summary = summarize(rows, stats.seed, stats.resamples, stats.confidence)
        _write_csv(summary, d / "summary.csv")
        _write_tex(summary, [("variant", "Variant"), ("arm", "Arm"), ("truncation", "Trunc."),
                             ("repeat", "Rep."), ("cases_reachable", "Reach."),
                             ("coverage_event_reachable", "Cov. (event)"),
                             ("coverage_ci_low", "CI low"), ("coverage_ci_high", "CI high"),
                             ("citation_precision_event", "Cit. prec."),
                             ("unsupported_claim_rate", "Unsupp."), ("verdict_accuracy", "Verdict acc.")],
                   f"{label}: per variant and arm", d / "summary.tex")
        primary = [r for r in rows if r["truncation"] == primary_t and r["repeat"] == primary_r]
        comps = compare_family(primary, stats)
        _write_csv(comps, d / "comparisons.csv")
        _write_tex(comps, [("name", "Comparison"), ("metric", "Metric"), ("n", "n"),
                           ("difference", "Diff. (b-a)"), ("ci_low", "CI low"), ("ci_high", "CI high"),
                           ("p_value", "p"), ("p_holm", "p (Holm)")],
                   f"{label}: declared comparisons, {primary_t}, repeat {primary_r}",
                   d / "comparisons.tex")
        (d / "coverage.svg").write_text(_svg(summary, label, primary_t, primary_r), encoding="utf-8")
        runs = sorted({r["run_id"] for r in rows})
        freeze = None
        if freeze_path and Path(freeze_path).exists():
            freeze = json.loads(Path(freeze_path).read_text(encoding="utf-8"))["freeze_sha256"]
        (d / "provenance.json").write_text(json.dumps({
            "label": label, "generated_utc": datetime.now(timezone.utc).isoformat(),
            "runs_dir": Path(runs_dir).as_posix(), "run_ids": runs, "case_rows": len(rows),
            "statistics_config": Path(statistics_config).name, "freeze_sha256": freeze,
            "primary": {"truncation": primary_t, "repeat": primary_r},
            "prompt_revision": choice.chosen or "all",
            "prompt_revisions_present": choice.present}, indent=2) + "\n",
            encoding="utf-8")
        written += [str(d / n) for n in ("per_case.csv", "summary.csv", "summary.tex", "comparisons.csv",
                                          "comparisons.tex", "coverage.svg", "provenance.json")]
        readme_parts.append(
            f"## {label}\n\nFolder `{folder}/`: prompt revision {choice.chosen or 'all'}, "
            f"{len(runs)} runs, {len(rows)} case rows, "
            f"{len({r['scenario'] for r in rows})} scenarios, truncations "
            f"{', '.join(sorted({r['truncation'] for r in rows}))}, repeats "
            f"{', '.join(str(x) for x in sorted({r['repeat'] for r in rows}))}.\n")
    (out / "README.md").write_text(
        "# results/\n\nGenerated by `python -m app.main export-paper-assets`; every number here is "
        "computed from run files (`scores.json` per run directory), never typed in. Re-run the "
        "command to regenerate; do not edit these files by hand.\n\n"
        "Files per part: `per_case.csv` (one row per case, variant and score row), `summary.csv` / "
        "`summary.tex` (per truncation, repeat, variant and arm; coverage CI = 95% percentile "
        "bootstrap over cases, stratified by scenario), `comparisons.csv` / `comparisons.tex` (the "
        "family declared in experiments/config/statistics.json, paired bootstrap, Holm-adjusted), "
        "`coverage.svg` (headline coverage, single vs graph after the verifier), `provenance.json` "
        "(run ids).\n\nHeadline metric: coverage by event_label on alert-reachable phases. Arms: "
        "single and graph, each before and after the evidence verifier.\n\n"
        + "\n".join(readme_parts), encoding="utf-8")
    written.append(str(out / "README.md"))
    return written
